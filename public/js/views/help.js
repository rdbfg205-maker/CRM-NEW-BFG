export function helpBtn(key) {
  return el('a', { class: 'btn sm', href: '#/help?m=' + key, title: 'راهنمای این بخش' }, '❓ راهنما');
}

export function helpView(c) {
  const params = new URLSearchParams(((location.hash || '').split('?')[1]) || '');
  const initKey = params.get('m');
  const head = el('div', { class: 'page-head' },
    el('div', {}, el('h1', {}, 'راهنما'), el('div', { class: 'sub' }, 'آموزش استفاده از ماژول‌ها — جستجو کنید یا از فهرست انتخاب کنید')),
    el('div', { class: 'actions' },
      (() => {
        const inp = el('input', { class: 'input', placeholder: 'جستجو در راهنما…', style: 'width:240px' });
        inp.addEventListener('input', () => { state.q = inp.value.trim(); renderList(); });
        return inp;
      })(), helpBtn('quickstart')));
  c.append(head);
  const state = { q: '', active: initKey || 'quickstart' };
  const side = el('aside', { class: 'cal-side', style: 'width:270px; min-width:270px' });
  const content = el('section', { style: 'min-width:0; flex:1' });
  const wrap = el('div', { style: 'display:flex; gap:16px; align-items:flex-start' }, side, content);
  c.append(wrap);

  const navBox = el('div', { class: 'card' }, el('div', { class: 'card-b', style: 'padding:8px' }));
  side.append(navBox);

  function match(m) {
    if (!state.q) return true;
    const q = state.q;
    return (m.title + ' ' + m.desc + ' ' + m.features.join(' ') + ' ' + m.steps.join(' ') + ' ' + m.faq.map(f => f.q + ' ' + f.a).join(' ')).includes(q);
  }
  function renderList() {
    const box = navBox.querySelector('.card-b');
    clear(box);
    const items = HELP_DATA.filter(match);
    if (!items.length) { box.append(el('div', { class: 'muted small', style: 'padding:12px' }, 'موردی پیدا نشد.')); return; }
    for (const m of items) {
      const b = el('a', { class: 'nav-item' + (state.active === m.key ? ' active' : ''), href: '#/help?m=' + m.key, style: 'display:flex; margin:1px 4px; padding:7px 10px; border-radius:8px; font-size:13px', onclick: () => { state.active = m.key; renderAll(); } },
        el('span', { style: 'flex:1' }, m.icon + ' ' + m.title));
      box.append(b);
    }
  }
  function renderContent() {
    clear(content);
    const m = HELP_DATA.find(x => x.key === state.active) || HELP_DATA[0];
    const card = el('div', { class: 'card' },
      el('div', { class: 'card-h' }, el('h3', {}, m.icon + ' ' + m.title)),
      el('div', { class: 'card-b' },
        el('div', { class: 'muted', style: 'margin-bottom:12px; line-height:2' }, m.desc)));
    if (m.features && m.features.length) {
      card.children[1].append(el('h4', { class: 'mt-8' }, 'امکانات'));
      const ul = el('ul', { style: 'margin:8px 0 14px; padding-inline-start:20px; line-height:2.1' });
      for (const f of m.features) ul.append(el('li', {}, f));
      card.children[1].append(ul);
    }
    if (m.steps && m.steps.length) {
      card.children[1].append(el('h4', {}, 'آموزش مرحله‌به‌مرحله'));
      const ol = el('ol', { style: 'margin:8px 0 14px; padding-inline-start:22px; line-height:2.2' });
      m.steps.forEach((s, i) => ol.append(el('li', {}, s)));
      card.children[1].append(ol);
    }
    if (m.faq && m.faq.length) {
      card.children[1].append(el('h4', {}, 'پرسش‌های متداول (FAQ)'));
      for (const f of m.faq) {
        card.children[1].append(el('div', { class: 'alert info', style: 'margin-top:8px' },
          el('b', {}, 'س: ' + f.q), el('div', { class: 'mt-4' }, 'ج: ' + f.a)));
      }
    }
    content.append(card);
    // related modules quick links
    const rel = el('div', { class: 'flex wrap', style: 'gap:8px; margin-top:14px' }, el('b', { class: 'muted small' }, 'بخش‌های مرتبط:'));
    for (const k of ['dashboard', 'customers', 'quotes', 'invoices', 'calls', 'calendar']) {
      if (k !== m.key) rel.append(el('a', { class: 'btn sm', href: '#/help?m=' + k }, (HELP_DATA.find(x => x.key === k) || {}).title || k));
    }
    content.append(rel);
  }
  function renderAll() { renderList(); renderContent(); }
  renderAll();
}
